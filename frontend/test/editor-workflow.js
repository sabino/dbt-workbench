import {expect} from "@playwright/test";
import {join} from "node:path";
import {replaceEditorContent} from "./editor-actions.js";

export async function verifyEditorWorkflow({page, base, browserBase, output, modifier, job, confirmDiscard}) {
  const tabs = page.getByRole("navigation", {name: "Open files", exact: true});
  const input = page.locator(".file-editor-pane:not([hidden]) .cm-content");
  const save = page.getByRole("button", {name: "Save file", exact: true});
  const sqlMode = page.getByRole("button", {name: "SQL", exact: true});
  const ednMode = page.getByRole("button", {name: "EDN", exact: true});
  const path = "models/editor_roundtrip.sql";
  const fileUrl = `${base}/api/projects/demo-jaffle-shop/file?path=${path}`;
  const original = "-- Keep the original spacing and comment\nselect 7 as editor_value;\n";
  expect(await tabs.locator(":scope > button:last-child").getAttribute("aria-label")).toBe("New file");
  await tabs.getByRole("button", {name: "New file", exact: true}).click();
  await expect(tabs.locator(".file-tab.active .tab-dirty")).toHaveText("*");
  await replaceEditorContent(page, input, original, modifier);
  expect((await page.request.get(fileUrl)).status()).toBe(400);
  await input.press(`${modifier}+s`);
  const dialog = page.getByRole("dialog", {name: "Save file to project", exact: true});
  const newPath = page.getByLabel("New file path", {exact: true});
  await expect(newPath).toBeFocused();
  await newPath.fill("../outside.sql");
  await dialog.getByRole("button", {name: "Create file", exact: true}).click();
  await expect(dialog.locator(".save-file-error")).toBeVisible();
  await newPath.fill("models/orders.sql");
  await dialog.getByRole("button", {name: "Create file", exact: true}).click();
  await expect(dialog.locator(".save-file-error")).toContainText(/exist/i);
  await newPath.fill(path);
  await dialog.getByRole("button", {name: "Create file", exact: true}).click();
  await expect(dialog).toBeHidden();
  await expect(tabs.locator(".file-tab.active")).toContainText("editor_roundtrip.sql");
  await expect(save).toBeDisabled();
  expect((await (await page.request.get(fileUrl)).json()).content).toBe(original);
  const sqlText = await input.innerText();
  await ednMode.click();
  await expect(input).toContainText(":select");
  await expect(input).toContainText(":editor_value");
  await expect(save).toBeDisabled();
  await sqlMode.click();
  await expect(input).toHaveText(sqlText, {useInnerText: true});
  expect((await (await page.request.get(fileUrl)).json()).content).toBe(original);

  await replaceEditorContent(page, input, original + "-- Draft undo history\n", modifier);
  const draft = await input.innerText();
  await ednMode.click();
  await expect(input).toContainText(":select");
  await sqlMode.click();
  await expect(input).toHaveText(draft, {useInnerText: true});
  await input.press(`${modifier}+z`);
  await expect(input).toHaveText(sqlText, {useInnerText: true});
  await expect(save).toBeDisabled();
  await ednMode.click();
  await expect(input).toContainText(":select");
  await replaceEditorContent(page, input, "{:select [[8 :edn_saved]]}", modifier);
  await save.click();
  await expect(tabs.locator(".file-tab.active .tab-dirty")).toHaveCount(0);
  await expect(save).toBeDisabled();
  const compiled = (await (await page.request.get(fileUrl)).json()).content;
  expect(compiled).toContain("edn_saved");
  expect(compiled).not.toContain(":select");
  expect(compiled).not.toMatch(/:p\d+/);
  await expect(ednMode).toHaveClass(/selected/);
  await sqlMode.click();
  await expect(input).toContainText("edn_saved");
  await job(() => input.press("F5"));
  await expect(page.locator(".result-grid tbody td").last()).toHaveText("8");

  await input.press(`${modifier}+n`);
  await expect(tabs.locator(".file-tab.active")).toContainText("Untitled");
  await ednMode.click();
  await expect(ednMode).toHaveClass(/selected/);
  const preciseEdn = "{:select [[12345678901234567890.123456789012345678M :precise_amount] [123456789012345678901234567890N :precise_id]]}";
  await replaceEditorContent(page, input, preciseEdn, modifier);
  await page.getByRole("button", {name: "Format", exact: true}).click();
  await expect(input).toHaveText(/12345678901234567890\.123456789012345678M/);
  await expect(input).toHaveText(/123456789012345678901234567890N/);
  await expect(page.getByText("Formatting document…", {exact: true})).toHaveCount(0);
  expect(await input.innerText()).not.toBe(preciseEdn);
  await replaceEditorContent(page, input, "{:select [[[:param :answer] :native_edn]]}", modifier);
  const querySettings = page.getByRole("button", {name: "Query settings", exact: true});
  await querySettings.click();
  await page.getByLabel("Parameters", {exact: true}).fill('{"answer":9}');
  await querySettings.click();
  await input.press(`${modifier}+s`);
  await newPath.fill("models/editor_native.edn");
  await dialog.getByRole("button", {name: "Create file", exact: true}).click();
  await expect(dialog).toBeHidden();
  await expect(save).toBeDisabled();
  await expect(input).toHaveText("{:select [[9 :native_edn]]}");
  await querySettings.click();
  expect(JSON.parse(await page.getByLabel("Parameters", {exact: true}).inputValue())).toEqual({});
  await querySettings.click();
  await page.getByRole("button", {name: "SQL formatting", exact: true}).click();
  await page.getByLabel("Always format on mode switch", {exact: true}).check();
  await page.getByRole("button", {name: "SQL formatting", exact: true}).click();
  await sqlMode.click();
  await expect(input).toContainText("native_edn");
  await expect(save).toBeDisabled();
  await page.getByRole("button", {name: "SQL formatting", exact: true}).click();
  await page.getByLabel("Always format on mode switch", {exact: true}).uncheck();
  await page.getByRole("button", {name: "SQL formatting", exact: true}).click();
  await ednMode.click();
  await expect(input).toHaveText("{:select [[9 :native_edn]]}");
  await expect(save).toBeDisabled();

  await input.press(`${modifier}+p`);
  const search = page.getByLabel("Search commands", {exact: true});
  await expect(page.getByRole("dialog", {name: "Go to file", exact: true})).toBeVisible();
  await search.fill("editor_roundtrip.sql");
  await search.press("Enter");
  await expect(tabs.locator(".file-tab.active")).toContainText("editor_roundtrip.sql");
  await expect(input).toBeFocused();
  await input.press(`${modifier}+Shift+p`);
  await expect(page.getByRole("dialog", {name: "Commands", exact: true})).toBeVisible();
  await search.fill("> Show results");
  await search.press("Enter");
  await expect(page.getByRole("button", {name: "Results", exact: true}).first()).toHaveAttribute("aria-pressed", "true");
  await input.focus();
  await input.press(`${modifier}+p`);
  await search.press("Escape");
  await expect(input).toBeFocused();
  await input.press(`${modifier}+p`);
  const closeCenter = page.getByRole("button", {name: "Close command center", exact: true});
  await closeCenter.focus();
  await closeCenter.press("Enter");
  await expect(page.getByRole("dialog", {name: "Go to file", exact: true})).toBeHidden();
  await expect(tabs.locator(".file-tab.active")).toContainText("editor_roundtrip.sql");

  let releaseConversion;
  const gate = new Promise(resolve => { releaseConversion = resolve; });
  const convertUrl = `${browserBase}/api/projects/demo-jaffle-shop/query/convert`;
  const delayedSql = "SELECT 10 AS delayed_conversion";
  await replaceEditorContent(page, input, delayedSql, modifier);
  await page.route(convertUrl, async route => { await gate; await route.continue(); });
  const convertedResponse = page.waitForResponse(response => response.url() === convertUrl && response.request().method() === "POST");
  await ednMode.click();
  await expect(input).toHaveAttribute("contenteditable", "false");
  await tabs.getByRole("button", {name: "editor_native.edn", exact: true}).click();
  await expect(input).toContainText(":native_edn");
  releaseConversion();
  const validEdn = (await (await convertedResponse).json()).content;
  await expect(page.getByText("Translating document…", {exact: true})).toHaveCount(0);
  await page.unroute(convertUrl);
  await expect(tabs.locator(".file-tab.active")).toContainText("editor_native.edn");
  await expect(input).toContainText(":native_edn");
  await tabs.getByRole("button", {name: "editor_roundtrip.sql", exact: true}).click();
  await expect(input).toContainText(":select");
  await replaceEditorContent(page, input, "{:select [", modifier);
  await page.getByRole("button", {name: "Format", exact: true}).click();
  await expect(page.getByRole("alert")).toContainText("complete EDN value");
  await expect(input).toHaveText("{:select [");
  await page.getByRole("button", {name: "Dismiss error", exact: true}).click();
  await sqlMode.click();
  await expect(page.getByRole("alert")).toBeVisible();
  await expect(ednMode).toHaveClass(/selected/);
  await expect(input).toHaveText("{:select [");
  await page.getByRole("button", {name: "Dismiss error", exact: true}).click();
  await replaceEditorContent(page, input, validEdn, modifier);
  await sqlMode.click();
  await expect(input).toHaveText(delayedSql, {useInnerText: true});

  await page.getByRole("button", {name: "SQL formatting", exact: true}).click();
  const alwaysFormat = page.getByLabel("Always format on mode switch", {exact: true});
  await expect(alwaysFormat).not.toBeChecked();
  await alwaysFormat.check();
  await page.getByRole("button", {name: "SQL formatting", exact: true}).click();
  await replaceEditorContent(page, input, "select  11 as format_probe", modifier);
  await ednMode.click();
  await expect(input).toContainText(":select");
  await sqlMode.click();
  await expect(input).toContainText("SELECT");
  await expect(save).toBeEnabled();
  await page.getByRole("button", {name: "SQL formatting", exact: true}).click();
  await alwaysFormat.uncheck();
  await page.getByRole("button", {name: "SQL formatting", exact: true}).click();

  await page.getByRole("button", {name: "Search files and commands", exact: true}).click();
  const keyboardSettings = page.getByRole("button", {name: "Keyboard shortcuts", exact: true});
  await keyboardSettings.focus();
  await keyboardSettings.press("Enter");
  const shortcuts = page.getByRole("dialog", {name: "Keyboard shortcuts", exact: true});
  const formatRow = shortcuts.locator(".shortcut-row").filter({has: page.getByText("Format document", {exact: true})});
  await formatRow.getByRole("button", {name: "Assign", exact: true}).click();
  const capture = page.getByLabel("Capture shortcut for Format document", {exact: true});
  await capture.press(`${modifier}+s`);
  await expect(shortcuts.locator(".shortcut-feedback")).toContainText("Already assigned to Save file");
  await expect(formatRow.getByRole("button", {name: "Save", exact: true})).toBeDisabled();
  await capture.press(`${modifier}+l`);
  await expect(shortcuts.locator(".shortcut-feedback")).toContainText("reserved");
  await capture.press(`${modifier}+Shift+u`);
  await capture.press("Tab");
  await expect(formatRow.getByRole("button", {name: "Save", exact: true})).toBeFocused();
  await formatRow.getByRole("button", {name: "Save", exact: true}).press("Enter");
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("workbench.command-shortcuts.v1")))).toMatchObject({"format-document": ["Mod+Shift+U"]});
  await page.screenshot({path: join(output, "keyboard-shortcuts.png"), fullPage: true});
  await page.getByRole("button", {name: "Close command center", exact: true}).click();
  await replaceEditorContent(page, input, "select  12 as shortcut_probe", modifier);
  await input.press("Alt+Shift+f");
  await expect(input).toHaveText("select  12 as shortcut_probe");
  await input.press(`${modifier}+Shift+u`);
  await expect(input).toContainText("SELECT");
  await input.press(`${modifier}+s`);
  await expect(tabs.locator(".file-tab.active .tab-dirty")).toHaveCount(0);
  await expect(save).toBeDisabled();
  await input.press(`${modifier}+w`);
  await expect(tabs.getByRole("button", {name: "editor_roundtrip.sql", exact: true})).toHaveCount(0);
  await input.press(`${modifier}+n`);
  const untitled = await tabs.locator(".file-tab.active > button:first-child").getAttribute("aria-label");
  await input.press(`${modifier}+w`);
  await expect(tabs.getByRole("button", {name: untitled, exact: true})).toBeVisible();
  confirmDiscard(true);
  await input.press(`${modifier}+w`);
  confirmDiscard(false);
  await expect(tabs.getByRole("button", {name: untitled, exact: true})).toHaveCount(0);

  await page.reload();
  await expect(page.getByLabel("Target", {exact: true})).toBeVisible();
  await input.press(`${modifier}+p`);
  await search.fill("editor_roundtrip.sql");
  await search.press("Enter");
  await expect(input).toContainText("shortcut_probe");
  await job(() => input.press("F5"));
  await expect(page.locator(".result-grid tbody td").last()).toHaveText("12");
  await replaceEditorContent(page, input, "select 13 as persisted_shortcut", modifier);
  await input.press(`${modifier}+Shift+u`);
  await expect(input).toContainText("SELECT");
  await input.press(`${modifier}+s`);
  await expect(tabs.locator(".file-tab.active .tab-dirty")).toHaveCount(0);
  await expect(save).toBeDisabled();
  await page.getByRole("button", {name: "SQL formatting", exact: true}).click();
  await expect(alwaysFormat).not.toBeChecked();
  await page.getByRole("button", {name: "SQL formatting", exact: true}).click();
  await tabs.getByRole("button", {name: "New file", exact: true}).click();
  const customerMetrics = "-- Customer purchase activity\nSELECT\n  customer_id,\n  COUNT(*) AS order_count,\n  SUM(amount) AS revenue,\n  ROUND(AVG(amount), 2) AS average_order_value\nFROM orders\nGROUP BY customer_id\nORDER BY revenue DESC";
  await replaceEditorContent(page, input, customerMetrics, modifier);
  await job(() => input.press("F5"));
  await input.press("Escape");
  await page.screenshot({path: join(output, "editor-workspace.png"), fullPage: true});
  await ednMode.click();
  await expect(input).toContainText(":group-by");
  await page.screenshot({path: join(output, "edn-workspace.png"), fullPage: true});
  await sqlMode.click();
  await expect(input).toHaveText(customerMetrics, {useInnerText: true});
  await input.press(`${modifier}+p`);
  await search.fill("customers");
  await page.screenshot({path: join(output, "command-center.png"), fullPage: true});
  await search.press("Escape");
}
